import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const config=JSON.parse(readFileSync(path.join(root,'mobile/app.config.json'),'utf8'));
const website=new URL(config.websiteUrl);
if(website.protocol!=='https:'||website.username||website.password||website.search||website.hash)throw Error('Configure a public HTTPS website URL.');
if(!/^[a-z][a-z0-9]*(\.[a-z][a-z0-9]*){2,}$/.test(config.appId))throw Error('Configure a valid reverse-domain app ID.');
const xml=value=>String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
const target=path.join(root,'mobile/ios');mkdirSync(target,{recursive:true});
writeFileSync(path.join(target,'project.yml'),`# Generated by npm run app:ios:prepare from mobile/app.config.json.
name: MembershipManagement
options:
  deploymentTarget:
    iOS: "16.0"
settings:
  base:
    SWIFT_VERSION: "5.0"
    PRODUCT_BUNDLE_IDENTIFIER: ${JSON.stringify(config.appId)}
    MARKETING_VERSION: ${JSON.stringify(config.versionName)}
    CURRENT_PROJECT_VERSION: ${JSON.stringify(String(config.versionCode))}
    TARGETED_DEVICE_FAMILY: "1,2"
    CODE_SIGN_STYLE: Automatic
targets:
  MembershipManagement:
    type: application
    platform: iOS
    sources:
      - path: MembershipApp
        excludes: [Info.plist]
      - path: ../app.config.json
        buildPhase: resources
      - path: ../android/app/src/main/assets/native.js
        buildPhase: resources
    info:
      path: MembershipApp/Info.plist
    settings:
      base:
        ASSETCATALOG_COMPILER_APPICON_NAME: AppIcon
schemes:
  MembershipManagement:
    build:
      targets:
        MembershipManagement: all
`);
const strings={CFBundleDisplayName:config.appName,CFBundleName:config.appName,CFBundleIdentifier:'$(PRODUCT_BUNDLE_IDENTIFIER)',CFBundleExecutable:'$(EXECUTABLE_NAME)',CFBundlePackageType:'APPL',CFBundleShortVersionString:config.versionName,CFBundleVersion:config.versionCode,NSCameraUsageDescription:'Scan membership QR passes to record attendance.',NSPhotoLibraryUsageDescription:'Choose member photos and QR images to upload.'};
writeFileSync(path.join(target,'MembershipApp/Info.plist'),'<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0"><dict>\n'+Object.entries(strings).map(([key,value])=>`<key>${key}</key><string>${xml(value)}</string>`).join('\n')+'\n<key>UILaunchScreen</key><dict/><key>UIRequiresFullScreen</key><false/>\n<key>UISupportedInterfaceOrientations</key><array><string>UIInterfaceOrientationPortrait</string><string>UIInterfaceOrientationLandscapeLeft</string><string>UIInterfaceOrientationLandscapeRight</string></array>\n</dict></plist>\n');
console.log('iPhone configuration prepared. On a Mac: cd mobile/ios && xcodegen generate && open MembershipManagement.xcodeproj');
