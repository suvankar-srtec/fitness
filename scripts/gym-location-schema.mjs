export async function ensureGymLocationSchema(sql){
 await sql.transaction([
  sql`CREATE TABLE IF NOT EXISTS gym_locations(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,admin_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,name TEXT NOT NULL CHECK(length(trim(name)) BETWEEN 1 AND 120),UNIQUE(id,admin_id))`,
  sql`CREATE UNIQUE INDEX IF NOT EXISTS gym_locations_name ON gym_locations(admin_id,lower(name))`,
  sql`ALTER TABLE users ADD COLUMN IF NOT EXISTS location_id INTEGER`,
  sql`ALTER TABLE members ADD COLUMN IF NOT EXISTS location_id INTEGER`,
  sql`ALTER TABLE users DROP CONSTRAINT IF EXISTS users_location_owner_fk`,
  sql`ALTER TABLE users ADD CONSTRAINT users_location_owner_fk FOREIGN KEY(location_id,created_by) REFERENCES gym_locations(id,admin_id)`,
  sql`ALTER TABLE members DROP CONSTRAINT IF EXISTS members_location_owner_fk`,
  sql`ALTER TABLE members ADD CONSTRAINT members_location_owner_fk FOREIGN KEY(location_id,admin_id) REFERENCES gym_locations(id,admin_id)`
 ]);
}
