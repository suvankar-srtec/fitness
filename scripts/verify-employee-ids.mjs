import nextEnv from '@next/env';
import {neon} from '@neondatabase/serverless';
import {ensureEmployeeSchema} from './employee-schema.mjs';
nextEnv.loadEnvConfig(process.cwd());
const sql=neon(process.env.DATABASE_URL);
let migration;const capture=(strings,...values)=>sql(strings,...values);capture.transaction=queries=>{migration=queries;return Promise.resolve();};
await ensureEmployeeSchema(capture);
try{
 await sql.transaction([
 sql`CREATE TEMP TABLE users(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT,gym_name TEXT,role TEXT,created_by INTEGER,location_id INTEGER,public_id TEXT UNIQUE) ON COMMIT DROP`,
 sql`CREATE TEMP TABLE gym_locations(id INTEGER PRIMARY KEY,admin_id INTEGER,name TEXT) ON COMMIT DROP`,
 sql`CREATE TEMP SEQUENCE gym_employee_ids`,
 ...migration,
 sql`CREATE TRIGGER gym_assign_user_id BEFORE INSERT ON users FOR EACH ROW EXECUTE FUNCTION gym_user_id_trigger()`,
 sql`DO $$ DECLARE first_id TEXT; second_id TEXT; large_id TEXT; BEGIN
 INSERT INTO users(id,name,gym_name,role,public_id) VALUES(100,'Owner','Fit Fusion','admin','ad01');
 INSERT INTO gym_locations(id,admin_id,name) VALUES(3,100,'Dum Dum');
 INSERT INTO users(name,role,created_by,location_id) VALUES('One','manager',100,3) RETURNING public_id INTO first_id;
 INSERT INTO users(name,role,created_by,location_id,public_id) VALUES('Two','supervisor',100,3,'sup99') RETURNING public_id INTO second_id;
 ASSERT first_id='EMP-FITFUSION-DUMDUM-00001','Manager ID must include EMP, gym, location and code';
 ASSERT second_id='EMP-FITFUSION-DUMDUM-00002','Supervisor ID must use the same EMP namespace';
 UPDATE users SET role='manager' WHERE public_id=second_id;
 ASSERT EXISTS(SELECT 1 FROM users WHERE public_id=second_id AND role='manager'),'Role changes must preserve the public ID';
 PERFORM setval('pg_temp.gym_employee_ids',99999);
 SELECT gym_new_employee_id(100,3) INTO large_id;
 ASSERT large_id='EMP-FITFUSION-DUMDUM-100000','Large sequence values must not be truncated';
 BEGIN
 PERFORM gym_new_employee_id(100,99);
 RAISE EXCEPTION 'Foreign location was accepted';
 EXCEPTION WHEN raise_exception THEN IF SQLERRM<>'INVALID_GYM_LOCATION' THEN RAISE;END IF;END;
 RAISE EXCEPTION 'EMPLOYEE_ID_TESTS_PASSED_ROLLBACK';
 END; $$`
 ]);
 throw Error('Rollback sentinel missing');
}catch(error){if(error.message!=='EMPLOYEE_ID_TESTS_PASSED_ROLLBACK')throw error;console.log('Employee ID database checks passed; all test data and schema changes rolled back.');}
